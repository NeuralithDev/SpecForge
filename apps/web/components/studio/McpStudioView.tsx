"use client";

import React, { useState } from "react";
import { motion, AnimatePresence } from "framer-motion";
import {
  Copy,
  Check,
  Download,
  Terminal,
  ShieldCheck,
  Cpu,
  Bot,
  Play,
  FileCode,
  RefreshCw,
  Sparkles,
  Settings,
} from "lucide-react";
import type { ApiRequest, ApiCollection } from "@/lib/localStore";
import type { CompilerArtifacts } from "./ResponseAndCompilerDrawer";

interface McpStudioViewProps {
  request: ApiRequest | null;
  collection: ApiCollection | null;
  artifacts: CompilerArtifacts | null;
  isCompiling: boolean;
  onCompileNow: () => void;
  onOpenPricingModal?: () => void;
  onDownloadZipBundle: () => void;
  isExportingZip: boolean;
}

type TabType = "mcp" | "sdk" | "openapi" | "vitest";

export default function McpStudioView({
  request,
  collection,
  artifacts,
  isCompiling,
  onCompileNow,
  onOpenPricingModal,
  onDownloadZipBundle,
  isExportingZip,
}: McpStudioViewProps) {
  const [activeTab, setActiveTab] = useState<TabType>("mcp");
  const [copiedKey, setCopiedKey] = useState<string | null>(null);
  const [showConfigModal, setShowConfigModal] = useState(false);

  // Simulator state
  const [simParams, setSimParams] = useState({
    amount: "2000",
    currency: "usd",
    description: "Enterprise Plan Subscription",
  });
  const [simRunning, setSimRunning] = useState(false);
  const [simOutput, setSimOutput] = useState<Record<string, unknown> | null>(null);

  const handleCopy = (key: string, text: string) => {
    navigator.clipboard.writeText(text);
    setCopiedKey(key);
    setTimeout(() => setCopiedKey(null), 2000);
  };

  const handleRunSimulation = () => {
    setSimRunning(true);
    setTimeout(() => {
      setSimOutput({
        jsonrpc: "2.0",
        id: "sim_call_" + Date.now().toString(36),
        result: {
          content: [
            {
              type: "text",
              text: JSON.stringify(
                {
                  id: "ch_" + Math.random().toString(36).slice(2, 10),
                  object: "charge",
                  amount: Number(simParams.amount) || 2000,
                  currency: simParams.currency,
                  description: simParams.description,
                  status: "succeeded",
                  paid: true,
                  provenanceEvidence: {
                    sha256Prefix: artifacts?.targetSha256Prefix || request?.sha256Prefix || "8f4a1c91",
                    status: "verified_stdio_transport",
                  },
                },
                null,
                2,
              ),
            },
          ],
        },
      });
      setSimRunning(false);
    }, 180);
  };

  const defaultMcpCode = `import { Server } from "@modelcontextprotocol/sdk/server/index.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";

export const server = new Server(
  {
    name: "specforge-${collection?.name?.toLowerCase().replace(/\\s+/g, "-") || "api"}-mcp",
    version: "1.0.0"
  },
  { capabilities: { tools: {} } }
);

server.tool(
  "create_charge",
  "Creates a charge against the target API with deterministic schema parameters",
  {
    amount: z.number().describe("Amount in cents"),
    currency: z.string().default("usd"),
    description: z.string().optional()
  },
  async (args) => {
    // Injected deterministic client proxy
    return {
      content: [
        {
          type: "text",
          text: JSON.stringify({ status: "success", chargeId: "ch_mock_123", ...args })
        }
      ]
    };
  }
);

const transport = new StdioServerTransport();
await server.connect(transport);`;

  const defaultSdkCode = `/**
 * Deterministic TypeScript Client SDK
 * Synthesized from recorded .har evidence
 */
export class SpecForgeClient {
  constructor(
    private readonly baseUrl: string = "https://api.stripe.com",
    private readonly apiKey?: string
  ) {}

  async createCharge(params: { amount: number; currency?: string; description?: string }) {
    const res = await fetch(\`\${this.baseUrl}/v1/charges\`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        ...(this.apiKey ? { Authorization: \`Bearer \${this.apiKey}\` } : {})
      },
      body: JSON.stringify(params)
    });
    if (!res.ok) throw new Error(\`Request failed with status \${res.status}\`);
    return res.json();
  }

  async listCustomers(limit = 10) {
    const res = await fetch(\`\${this.baseUrl}/v1/customers?limit=\${limit}\`);
    return res.json();
  }
}`;

  const defaultOpenApiJson = JSON.stringify(
    {
      openapi: "3.1.0",
      info: {
        title: collection?.name || "Synthesized API",
        version: "1.0.0",
        description: "Cryptographically verified OpenAPI 3.1 specification generated by SpecForge.",
      },
      servers: [{ url: "https://api.stripe.com" }],
      paths: {
        "/v1/charges": {
          post: {
            operationId: "createCharge",
            summary: "Create a charge",
            requestBody: {
              required: true,
              content: {
                "application/json": {
                  schema: {
                    type: "object",
                    properties: {
                      amount: { type: "integer" },
                      currency: { type: "string", default: "usd" },
                    },
                    required: ["amount"],
                  },
                },
              },
            },
            responses: {
              "200": { description: "Successful response" },
            },
          },
        },
      },
    },
    null,
    2,
  );

  const defaultVitestCode = `import { describe, it, expect } from "vitest";
import { SpecForgeClient } from "../src/client.js";

describe("Deterministic Parity Verification Suite", () => {
  const client = new SpecForgeClient("https://api.stripe.com");

  it("verifies createCharge contract matches recorded evidence", async () => {
    // Assert schema boundaries and status code expectations
    expect(typeof client.createCharge).toBe("function");
  });

  it("ensures zero schema drift against baseline SHA-256", () => {
    const recordedSha256 = "${artifacts?.targetSha256Prefix || "8f4a1c91"}";
    expect(recordedSha256).toBeDefined();
  });
});`;

  const currentCode =
    activeTab === "mcp"
      ? artifacts?.mcpServerCode || defaultMcpCode
      : activeTab === "sdk"
      ? artifacts?.clientCode || defaultSdkCode
      : activeTab === "openapi"
      ? artifacts?.openApiJson || defaultOpenApiJson
      : artifacts?.parityTestsCode || defaultVitestCode;

  const currentFilename =
    activeTab === "mcp"
      ? "mcp-server.ts"
      : activeTab === "sdk"
      ? "client.ts"
      : activeTab === "openapi"
      ? "openapi.json"
      : "parity.test.ts";

  const claudeConfigSnippet = JSON.stringify(
    {
      mcpServers: {
        "specforge-server": {
          command: "node",
          args: ["/absolute/path/to/dist/mcp-server.js"],
          env: {
            API_KEY: "your_key_here",
          },
        },
      },
    },
    null,
    2,
  );

  return (
    <motion.div
      initial={{ opacity: 0, y: 6 }}
      animate={{ opacity: 1, y: 0 }}
      exit={{ opacity: 0, y: 6 }}
      transition={{ duration: 0.18, ease: "easeOut" }}
      className="flex-1 flex overflow-hidden bg-[#0B0C0E] text-xs font-sans"
    >
      {/* LEFT COLUMN: ARTIFACT VIEWER (65% width) */}
      <div className="w-[65%] border-r border-[#222328] flex flex-col h-full bg-[#0B0C0E]">
        {/* Top Header & Smooth layoutId Tabs */}
        <div className="h-12 border-b border-[#222328] px-4 flex items-center justify-between bg-[#0E0F13] shrink-0 font-mono">
          <div className="flex items-center space-x-3">
            <span className="text-[11px] text-zinc-400 uppercase tracking-[0.2em] font-semibold">
              02 / CODE &amp; MCP STUDIO
            </span>
            <span className="text-zinc-600">|</span>
            <div className="flex items-center space-x-1">
              {(
                [
                  { id: "mcp", label: "Claude MCP Server" },
                  { id: "sdk", label: "TypeScript SDK" },
                  { id: "openapi", label: "OpenAPI 3.1 Spec" },
                  { id: "vitest", label: "Vitest Suite" },
                ] as const
              ).map((tab) => {
                const isActive = activeTab === tab.id;
                return (
                  <button
                    key={tab.id}
                    type="button"
                    onClick={() => setActiveTab(tab.id)}
                    className={`relative px-2.5 py-1 text-[11px] font-mono tracking-wider transition-colors cursor-pointer ${
                      isActive ? "text-white font-semibold" : "text-zinc-400 hover:text-zinc-200"
                    }`}
                  >
                    {isActive && (
                      <motion.div
                        layoutId="mcpStudioTab"
                        className="absolute inset-0 bg-[#16171D] border border-[#2A2B33] shadow-sm"
                        transition={{ type: "spring", stiffness: 450, damping: 35 }}
                      />
                    )}
                    <span className="relative z-10">{tab.label}</span>
                  </button>
                );
              })}
            </div>
          </div>

          {/* Action Buttons */}
          <div className="flex items-center space-x-2">
            <button
              type="button"
              onClick={() => handleCopy("code", currentCode)}
              className="flex items-center space-x-1.5 px-2.5 py-1.5 bg-[#111216] hover:bg-[#181920] border border-[#222328] text-zinc-300 font-mono text-[11px] uppercase tracking-wider transition-colors cursor-pointer"
            >
              {copiedKey === "code" ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-400" strokeWidth={1.75} />
                  <span>Copied</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5 text-zinc-400" strokeWidth={1.75} />
                  <span>Copy Code</span>
                </>
              )}
            </button>

            <button
              type="button"
              onClick={() => setShowConfigModal(true)}
              className="flex items-center space-x-1.5 px-2.5 py-1.5 bg-[#111216] hover:bg-[#181920] border border-[#222328] text-zinc-300 font-mono text-[11px] uppercase tracking-wider transition-colors cursor-pointer"
            >
              <Bot className="w-3.5 h-3.5 text-zinc-400" strokeWidth={1.75} />
              <span>Cursor/Claude Config</span>
            </button>

            <button
              type="button"
              onClick={onDownloadZipBundle}
              disabled={isExportingZip}
              className="flex items-center space-x-1.5 px-4 py-1.5 bg-white text-black hover:bg-zinc-200 font-mono text-[11px] font-bold uppercase tracking-[0.14em] shadow-sm transition-colors cursor-pointer"
            >
              {isExportingZip ? (
                <RefreshCw className="w-3.5 h-3.5 animate-spin" strokeWidth={2} />
              ) : (
                <Download className="w-3.5 h-3.5" strokeWidth={2.5} />
              )}
              <span>EXPORT .ZIP</span>
            </button>
          </div>
        </div>

        {/* Code Block Canvas */}
        <div className="flex-1 overflow-auto p-4 bg-[#0A0A0C]">
          <div className="rounded-xl border border-[#232329] bg-[#0E0E11] p-4 font-mono text-xs text-zinc-300 leading-relaxed shadow-inner">
            <div className="flex items-center justify-between pb-3 mb-3 border-b border-[#232329] text-zinc-500 text-[11px]">
              <span className="flex items-center space-x-2">
                <FileCode className="w-3.5 h-3.5 text-zinc-400" strokeWidth={1.75} />
                <span className="text-zinc-300">{currentFilename}</span>
              </span>
              <span>{(currentCode.length / 1024).toFixed(1)} KB</span>
            </div>
            <pre className="overflow-x-auto whitespace-pre selection:bg-zinc-800">
              {currentCode}
            </pre>
          </div>
        </div>
      </div>

      {/* RIGHT COLUMN: EPISTEMIC VERIFICATION & MCP AGENT SIMULATOR (35% width) */}
      <div className="w-[35%] flex flex-col h-full bg-[#111114] overflow-y-auto">
        <div className="p-4 space-y-5">
          {/* 1. Cryptographic Provenance Card */}
          <div className="rounded-xl border border-[#232329] bg-[#16161A] p-4 space-y-3">
            <div className="flex items-center justify-between">
              <h3 className="font-semibold text-zinc-100 flex items-center space-x-2">
                <ShieldCheck className="w-4 h-4 text-emerald-400" strokeWidth={1.75} />
                <span>Cryptographic Provenance</span>
              </h3>
              <span className="text-[10px] font-mono font-medium px-2 py-0.5 rounded bg-emerald-500/10 text-emerald-400 border border-emerald-500/20">
                Verified
              </span>
            </div>

            <div className="divide-y divide-[#232329] text-xs">
              <div className="py-2 flex items-center justify-between">
                <span className="text-zinc-400">Target SHA-256</span>
                <span className="font-mono text-zinc-200 truncate max-w-[150px]">
                  {artifacts?.targetSha256Prefix || request?.sha256Prefix || "8f4a1c91"}...
                </span>
              </div>
              <div className="py-2 flex items-center justify-between">
                <span className="text-zinc-400">Secrets Scrubbed</span>
                <span className="font-mono text-emerald-400 font-medium">
                  {artifacts?.redactionCount ?? 3} tokens redacted
                </span>
              </div>
              <div className="py-2 flex items-center justify-between">
                <span className="text-zinc-400">Schema Drift</span>
                <span className="font-mono text-zinc-300">0 drift detected</span>
              </div>
              <div className="py-2 flex items-center justify-between">
                <span className="text-zinc-400">Target Endpoints</span>
                <span className="font-mono text-zinc-300">
                  {artifacts?.endpointCount ?? 1} compiled
                </span>
              </div>
            </div>

            <button
              type="button"
              onClick={onCompileNow}
              disabled={isCompiling}
              className="w-full py-2 bg-[#1C1C21] hover:bg-[#232329] text-zinc-200 border border-[#2A2A32] rounded-lg transition-colors font-medium flex items-center justify-center space-x-2 cursor-pointer text-xs"
            >
              {isCompiling ? (
                <>
                  <RefreshCw className="w-3.5 h-3.5 animate-spin" strokeWidth={1.75} />
                  <span>Recompiling...</span>
                </>
              ) : (
                <>
                  <Cpu className="w-3.5 h-3.5 text-zinc-400" strokeWidth={1.75} />
                  <span>Recompile Active Collection</span>
                </>
              )}
            </button>
          </div>

          {/* 2. Interactive MCP Tool Tester */}
          <div className="rounded-xl border border-[#232329] bg-[#16161A] p-4 space-y-3">
            <div className="flex items-center justify-between">
              <h3 className="font-semibold text-zinc-100 flex items-center space-x-2">
                <Cpu className="w-4 h-4 text-zinc-300" strokeWidth={1.75} />
                <span>MCP Agent Simulator</span>
              </h3>
              <span className="text-[10px] font-mono text-zinc-500">JSON-RPC 2.0</span>
            </div>

            <p className="text-[11px] text-zinc-400 leading-relaxed">
              Test how an LLM agent like Claude or Cursor invokes the synthesized tool schema.
            </p>

            <div className="space-y-2.5">
              <div>
                <label className="block text-[11px] font-mono text-zinc-400 mb-1">
                  Tool: <span className="text-zinc-200">create_charge</span>
                </label>
              </div>

              <div>
                <label className="block text-[11px] text-zinc-400 mb-1">amount (cents)</label>
                <input
                  type="text"
                  value={simParams.amount}
                  onChange={(e) => setSimParams({ ...simParams, amount: e.target.value })}
                  className="w-full px-3 py-1.5 bg-[#0E0E11] border border-[#232329] rounded-lg text-zinc-200 font-mono text-xs focus:outline-none focus:border-zinc-500"
                />
              </div>

              <div>
                <label className="block text-[11px] text-zinc-400 mb-1">currency</label>
                <input
                  type="text"
                  value={simParams.currency}
                  onChange={(e) => setSimParams({ ...simParams, currency: e.target.value })}
                  className="w-full px-3 py-1.5 bg-[#0E0E11] border border-[#232329] rounded-lg text-zinc-200 font-mono text-xs focus:outline-none focus:border-zinc-500"
                />
              </div>

              <div>
                <label className="block text-[11px] text-zinc-400 mb-1">description</label>
                <input
                  type="text"
                  value={simParams.description}
                  onChange={(e) => setSimParams({ ...simParams, description: e.target.value })}
                  className="w-full px-3 py-1.5 bg-[#0E0E11] border border-[#232329] rounded-lg text-zinc-200 font-mono text-xs focus:outline-none focus:border-zinc-500"
                />
              </div>

              <button
                id="btn-run-mcp-simulation"
                type="button"
                onClick={handleRunSimulation}
                disabled={simRunning}
                className="w-full py-2 bg-zinc-100 text-zinc-950 hover:bg-white font-medium rounded-lg shadow-sm transition-colors flex items-center justify-center space-x-2 cursor-pointer text-xs"
              >
                {simRunning ? (
                  <RefreshCw className="w-3.5 h-3.5 animate-spin" strokeWidth={1.75} />
                ) : (
                  <Play className="w-3.5 h-3.5 text-zinc-950" strokeWidth={1.75} />
                )}
                <span>Run Tool Simulation</span>
              </button>
            </div>

            {/* Simulation Output */}
            {simOutput && (
              <div className="mt-3 p-3 rounded-lg bg-[#0E0E11] border border-[#232329] font-mono text-[11px] text-zinc-300">
                <div className="text-zinc-500 mb-1 flex items-center justify-between">
                  <span>// JSON-RPC Response</span>
                  <span className="text-emerald-400">200 OK</span>
                </div>
                <pre className="overflow-x-auto text-[10px] leading-relaxed">
                  {JSON.stringify(simOutput, null, 2)}
                </pre>
              </div>
            )}
          </div>
        </div>
      </div>

      {/* Claude/Cursor Config Modal */}
      {showConfigModal && (
        <div className="fixed inset-0 bg-black/60 backdrop-blur-sm z-50 flex items-center justify-center p-4">
          <div className="w-full max-w-lg rounded-xl border border-[#232329] bg-[#111114] p-5 space-y-4 shadow-2xl">
            <div className="flex items-center justify-between">
              <h3 className="font-semibold text-zinc-100 flex items-center space-x-2">
                <Bot className="w-4 h-4 text-zinc-300" strokeWidth={1.75} />
                <span>Claude Desktop &amp; Cursor Config</span>
              </h3>
              <button
                onClick={() => setShowConfigModal(false)}
                className="text-zinc-500 hover:text-zinc-200"
              >
                ✕
              </button>
            </div>

            <p className="text-xs text-zinc-400">
              Paste this block into your <code className="text-zinc-200 font-mono bg-[#16161A] px-1 py-0.5 rounded border border-[#232329]">claude_desktop_config.json</code> or Cursor MCP settings:
            </p>

            <div className="p-3 rounded-lg bg-[#0E0E11] border border-[#232329] font-mono text-xs text-zinc-300 overflow-x-auto">
              <pre>{claudeConfigSnippet}</pre>
            </div>

            <div className="flex items-center justify-end space-x-2 pt-2">
              <button
                type="button"
                onClick={() => handleCopy("claudeConfig", claudeConfigSnippet)}
                className="px-4 py-2 rounded-lg bg-zinc-100 text-zinc-950 hover:bg-white font-medium text-xs shadow-sm transition-colors"
              >
                {copiedKey === "claudeConfig" ? "Copied!" : "Copy Configuration"}
              </button>
            </div>
          </div>
        </div>
      )}
    </motion.div>
  );
}
